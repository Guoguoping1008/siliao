#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""0730 的主送机关修正。

【问题】API 读主送机关时**吞了两处**:
  1. 原文「…农村工作）**厅（局、**委）」-> 模型写成「…农村工作）**委**」
     (第 1 行行末是「农村工作）厅」, 第 2 行行首是「委」、发展改革委…)
  2. 原文「中国人民银行上海总部、**各分行、营业管理部、**各省会（首府）城市中心支行」
     -> 模型写成「中国人民银行上海总部、各省会（首府）城市中心支行」

【对策】目视核对后局部改写, 不重跑 API。
"""
import os
import sys

REPO = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(REPO, "minimax", "02制度文件", "09_（九）行业规划和政策",
                   "138_关于促进农业产业化联合体发展的指导意见", "0730.md")

OLD = ("各省、自治区、直辖市及新疆生产建设兵团农业（农牧、农村经济、农村工作）委、"
       "发展改革委、财政厅（局）、国土资源厅（局），中国人民银行上海总部、"
       "各省会（首府）城市中心支行，各省、自治区、直辖市及新疆生产建设兵团"
       "国家税务局、地方税务局：")

NEW = ("各省、自治区、直辖市及新疆生产建设兵团农业（农牧、农村经济、农村工作）"
       "厅（局、委）、发展改革委、财政厅（局）、国土资源厅（局），"
       "中国人民银行上海总部、各分行、营业管理部、各省会（首府）城市中心支行，"
       "各省、自治区、直辖市及新疆生产建设兵团国家税务局、地方税务局：")


def main():
    t = open(OUT, encoding="utf-8").read()
    if OLD not in t:
        if NEW in t:
            print("已经是修正后的版本, 无需改动")
            return 0
        print("!! 找不到待修正的主送机关行")
        return 1
    t = t.replace(OLD, NEW)
    open(OUT, "w", encoding="utf-8").write(t)
    print("已修正主送机关:")
    print("  + 厅（局、委）")
    print("  + 中国人民银行上海总部、各分行、营业管理部、")
    return 0


if __name__ == "__main__":
    sys.exit(main())
