def td(v="", attrs="", tag="td"):
    a = (" " + attrs) if attrs else ""
    return "<%s%s>%s</%s>" % (tag, a, v, tag)


def tr(cells):
    return "<tr>%s</tr>" % "".join(cells)


def build(rows, section=None, section_at=None):
    """rows: [(序号, 编号, 名称), ...]
    section: 表内的 colspan=3 分类标题行
    section_at: 该标题行插在第几行之前(0=表头后); None=最后
    """
    out = ['<table border="1">']
    # 表头: 「（续表）」在**标准名称表头格内**(原图就是这样)
    out.append(tr([td("序号", tag="th"), td("标准编号", tag="th"),
                   td("标准名称<br>" + CONT, tag="th")]))
    for i, r in enumerate(rows):
        if section and section_at is not None and i == section_at:
            out.append(tr([td(section, 'colspan="3"')]))
        out.append(tr([td(c) for c in r]))
    if section and section_at is None:
        out.append(tr([td(section, 'colspan="3"')]))
    out.append("</table>")
    out.append("")
    return "\n".join(out)


