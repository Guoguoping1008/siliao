def check(txt, must):
    errs = []
    for k in must:
        if k not in txt:
            errs.append("缺: " + k)
    for k in MUST_NOT:
        if k in txt:
            errs.append("不应出现: " + k)
    if txt.count("<table") != 1:
        errs.append("表数 != 1")
    m = re.findall(r"<table.*?</table>", txt, re.S)[0]
    rows = re.findall(r"<tr>(.*?)</tr>", m, re.S)
    for i, r in enumerate(rows, 1):
        tags = re.findall(r"<t[dh]([^>]*)>", r)
        width = 0
        for a in tags:
            mc = re.search(r'colspan="(\d+)"', a)
            width += int(mc.group(1)) if mc else 1
        if width != 3:
            errs.append("第 %d 行展开后列数 != 3, 实际 %d" % (i, width))
    # 序号连续(分类标题行会打断序列, 分段检查)
    seg = []
    for r in rows:
        cells = re.findall(r"<td[^>]*>(.*?)</td>", r, re.S)
        if cells and re.fullmatch(r"\d+", cells[0]):
            seg.append(int(cells[0]))
        else:
            if seg:
                for a, b in zip(seg, seg[1:]):
                    if b != a + 1:
                        errs.append("序号不连续: %d -> %d" % (a, b))
                seg = []
    if seg:
        for a, b in zip(seg, seg[1:]):
            if b != a + 1:
                errs.append("序号不连续: %d -> %d" % (a, b))
    return errs


