MUST_NOT = [
    "#### ",
    "首蓍干草粉",
    "碱式氯化锌",
    "水蓼叶粉",
]


def check(txt, must, name):
    errs = []
    for k in must:
        if k not in txt:
            errs.append("缺: " + k)
    for k in MUST_NOT:
        if k in txt:
            errs.append("不应出现: " + k)
    for m in re.findall(r"<table.*?</table>", txt, re.S):
        for i, r in enumerate(re.findall(r"<tr>(.*?)</tr>", m, re.S), 1):
            tags = re.findall(r"<t[dh]([^>]*)>", r)
            width = 0
            for a in tags:
                mc = re.search(r'colspan="(\d+)"', a)
                width += int(mc.group(1)) if mc else 1
            if width != 3:
                errs.append("表内第 %d 行展开后列数 != 3, 实际 %d" % (i, width))
    # 序号连续性: 每张表的数据行序号必须连续
    for m in re.findall(r"<table.*?</table>", txt, re.S):
        rows = re.findall(r"<tr>(.*?)</tr>", m, re.S)
        nums = []
        for r in rows:
            cells = re.findall(r"<td[^>]*>(.*?)</td>", r, re.S)
            if cells and re.fullmatch(r"\d+", cells[0]):
                nums.append(int(cells[0]))
        if nums:
            for a, b in zip(nums, nums[1:]):
                if b != a + 1:
                    errs.append("序号不连续: %d -> %d" % (a, b))
    return errs


