def td(v="", attrs="", tag="td"):
    a = (" " + attrs) if attrs else ""
    return "<%s%s>%s</%s>" % (tag, a, v, tag)


def tr(cells):
    return "<tr>%s</tr>" % "".join(cells)


def table(rows, section_rows=None, cont=False):
    """3 列表: 序号|标准编号|标准名称
    section_rows: 表内的 colspan=3 分类标题行(插在表头之后、数据行之前)
    """
    out = []
    if cont:
        out.append(CONT)
        out.append("")
    out.append('<table border="1">')
    out.append(tr([td("序号", tag="th"), td("标准编号", tag="th"),
                   td("标准名称", tag="th")]))
    for s in (section_rows or []):
        out.append(tr([td(s, 'colspan="3"')]))
    for r in rows:
        out.append(tr([td(c) for c in r]))
    out.append("</table>")
    return "\n".join(out)


