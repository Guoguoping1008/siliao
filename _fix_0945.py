def td(v="", attrs="", tag="td"):
    a = (" " + attrs) if attrs else ""
    return "<%s%s>%s</%s>" % (tag, a, v, tag)


def tr(cells):
    return "<tr>%s</tr>" % "".join(cells)


def build_table(head, rows, note):
    out = ['<table border="1">']
    out.append(tr([td(h, tag="th") for h in head]))
    for r in rows:
        out.append(tr([td(c) for c in r]))
    out.append(tr([td(note, 'colspan="4"')]))
    out.append("</table>")
    return "\n".join(out)


def build():
    t1 = build_table(T1_HEAD, T1_ROWS, T1_NOTE)
