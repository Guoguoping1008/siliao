def render(items):
    out = []
    for kind, text in items:
        if kind == "h1":
            out.append("# " + text)
            out.append("")
        elif kind == "h2":
            out.append("## " + text)
            out.append("")
        elif kind == "bold":
            out.append("**" + text + "**")
            out.append("")
        else:
            out.append(text)
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def check(txt, must):
    errs = []
    for k in must:
        if k not in txt:
            errs.append("缺: " + k)
    for k in MUST_NOT:
        if k in txt:
            errs.append("不应出现: " + k)
    # 章节标题必须独立成行
    for m in re.findall(r"(?m)^## ([一二三四五六七八九十]+、.+)$", txt):
        pass
    for m in re.finditer(r"(?m)^([一二三四五六七八九十]+、[^\n]{4,60})$", txt):
        if not txt[m.start():].startswith("## "):
            errs.append("章节标题未独立成 ## 行: " + m.group(1))
    return errs


