def check(txt):
    errs = []
    for k in MUST:
        if k not in txt:
            errs.append("缺: " + k)
    for k in MUST_NOT:
        if k in txt:
            errs.append("不应出现: " + k)
    # 章标题必须独立成行
    if not re.search(r"\n## 第五章　兽药进出口\n", txt):
        errs.append("章标题未独立成行")
    # 条标题必须独立成行
    for t in ("第二十九条", "第三十条", "第三十一条", "第三十二条",
              "第三十三条", "第三十四条", "第三十五条"):
        if not re.search(r"\n### " + t + r"[　 ]", txt):
            errs.append("条标题未独立成行: " + t)
    return errs


