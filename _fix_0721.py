def td(v="", attrs="", tag="td"):
    a = (" " + attrs) if attrs else ""
    return "<%s%s>%s</%s>" % (tag, a, v, tag)


def tr(cells):
    return "  <tr>\n    %s\n  </tr>" % "\n    ".join(cells)


def box(title, body):
    """专栏方框 —— **不是表格**, 用标题 + 段落。

    坑: 专栏在扫描件上**有外框**, 但框内**没有任何竖向分隔线**,
    只有「外框 + 标题下一条横线」—— 这是**文本框(text frame)**, 不是单元格网格。
    建成 <table> 会凭空造出不存在的行/列结构。
    """
    return "\n".join([
        "### %s" % title,
        "",
        body,
        "",
    ])


