MUST_NOT = [
    "<td>约束</td>",          # 末行的「约束」应是「必选」等
]


def check(txt, must, name):
    errs = []
    for k in must:
        if k not in txt:
            errs.append("缺: " + k)
    for k in MUST_NOT:
        if k in txt:
            errs.append("不应出现: " + k)
    if name in ("0974", "0975", "0976"):
        if "<table" in txt:
            errs.append("不该有表(这页是纯正文)")
    else:
        if txt.count("<table") != 1:
            errs.append("表数 != 1")
        rows = re.findall(r"<tr>(.*?)</tr>", txt, re.S)
        if len(rows) != 15:
            errs.append("行数 != 15 (表题1+表头3+数据10+末行1), 实际 %d" % len(rows))
        # 展开后每行 4 列
        remain = [0] * 4
        for i, m in enumerate(rows, 1):
            tags = re.findall(r"<t[dh]([^>]*)>", m)
            remain = [r - 1 if r > 0 else 0 for r in remain]
            col = 0
            placed = 0
            while placed < len(tags):
                if col >= 4:
                    break
                if remain[col] > 0:
                    col += 1
                    continue
                a = tags[placed]
                mc = re.search(r'colspan="(\d+)"', a)
                cs = int(mc.group(1)) if mc else 1
                mr = re.search(r'rowspan="(\d+)"', a)
                rs = int(mr.group(1)) if mr else 1
                for c in range(col, min(4, col + cs)):
                    remain[c] = rs
                col += cs
                placed += 1
            if placed != len(tags) or col != 4:
                errs.append("第 %d 行展开后列数 != 4 (放了 %d/%d 格, 到第 %d 列)"
                            % (i, placed, len(tags), col))
    return errs


